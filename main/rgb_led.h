#pragma once

#include "esp_err.h"

/* 初始化板载 RGB LED（只建 RMT 句柄，幂等，可重复调用）。ROM 装载后调用一次。 */
esp_err_t rgb_led_init(void);

/* 把「实际帧率 / 目标帧率」的百分比（0~100，100 表示满帧）分三档映射成
 * 绿/蓝/红三个原生色并刷新一次。每个模拟器每秒统计一次帧率时顺手调用即可，
 * 不需要额外的定时任务。rgb_led_init() 没成功时静默跳过。
 *
 * 没用 CPU 占用率（"CPU 余量"）是因为实测那个数字跟着 ROM 走、同一个游戏
 * 里基本不变，玩起来灯像是死的；帧率达成率能反映真正的卡顿。 */
void rgb_led_report_perf(int percent);

/* 立即熄灭状态灯。退出游戏、esp_restart() 重启回菜单之前必须调用——重启
 * 会清掉软件这边的计时状态，但 WS2812 灯珠是独立芯片，没人发新数据就会
 * 保持重启前最后一次的颜色，一直亮到菜单画面上。 */
void rgb_led_off(void);
